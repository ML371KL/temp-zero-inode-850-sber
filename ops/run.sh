#!/usr/bin/env bash
#
# Один вход для всех тактов панели «Сбер 850» (схема Ленты, каркас — 850oa).
#
#     run.sh collect         утро: сбор источников (даты и формы ЦБ, T-Invest, ISS,
#                            ЦБ, лента новостей) с повтором внутри такта, если
#                            отказал невосполнимый источник; по понедельникам —
#                            тесты такта «в будущем» (FAKE_TODAY = сегодня + 60
#                            дней), объём и здоровье состояния
#     run.sh release-watch   дни релизов, каждые 10 минут 09:45–13:00 МСК: тихая
#                            проверка окна; дозор релизов РСБУ и МСФО; принят
#                            новый месяц РСБУ или кандидат МСФО — нау-каст, тесты
#                            такта, сборка, публикация, сверка
#     run.sh daily           будни вечером: сбор рядов и цен → нау-каст → тесты
#                            такта → сборка → публикация → сверка
#     run.sh rebuild         раз в 15 минут: тихая проверка; если с опубликованного
#                            выпуска изменился код (CODE_DIRS) — тесты такта,
#                            сборка, публикация, сверка; дожимает сверку прошлого
#                            такта; БЕЗ сбора и нау-каста
#     run.sh rollback <sha> ["причина"]
#                            вернуть на витрину прошлый выпуск (под тем же замком)
#
# КАНАЛ ДАННЫХ (docs/INTERFACES.md §6): сборка кладёт выпуск в
# $BANK_STATE_DIR/release/latest.json, `ops/publish.py` дописывает его в ветку
# `release` публичного репозитория данных (GitHub Pages), функция
# `functions/api/model.js` отдаёт его браузеру. Сверка читает выпуск через ту же
# боевую дверь, что и браузер.
#
# ГЛАВНОЕ ПРАВИЛО: упавший шаг означает, что на витрину НИЧЕГО не уходит.
# Прежний выпуск остаётся валидным, а витрина сама покажет возраст данных.
#
# КОДЫ ВОЗВРАТА — ЕДИНСТВЕННЫЙ КАНАЛ ТРЕВОГ. `ExecStopPost` каждого юнита зовёт
# общий мост /usr/local/sbin/dash-alert, а тот шлёт в Telegram СМЕНУ состояния
# по коду юнита:
#     0   — прошло, тревожить не о чем;
#     1   — ПРОВАЛ: упал шаг, выпуска нет (выше в журнале — «ПРОВАЛ на шаге «…»»);
#     8   — ТРЕВОГА: все шаги выполнены (выпуск, если такт его делает, на
#           витрине), но прогон требует внимания; последняя строка журнала —
#           «ТРЕВОГА (код 8): <причины>». Внутри такта это код 3 шагов
#           (невосполнимый источник не добран, тревога сборки, сверка не
#           дождалась выпуска, «будущее» краснеет): причины копятся и уходят
#           одним кодом; других кодов тревоги нет (docs/INTERFACES.md §6).
#           В ШТАТНОМ СОСТОЯНИИ КАЖДЫЙ ТАКТ КОНЧАЕТСЯ КОДОМ 0: срок, о котором
#           достаточно знать заранее (объяснение гейта истекает, срок документа
#           эмитента истёк), — плашка выпуска, а не тревога;
#     64  — неверный режим или проба тревоги с чужим источником;
#     75  — другой такт держит замок дольше LOCK_WAIT_SECONDS;
#     78  — нет env-файла, в нём нет обязательной переменной или каталог кода
#           (SBER_REPO_DIR) — не клон git.
# ПОЛИТИКА ТРЕВОГ (docs/INTERFACES.md §6). Тревога — то, что требует человека и
# что повтор не снимет: юниты на коде 8 не перезапускаются
# (`RestartPreventExitStatus=8`). Повтор — только там, где он спасает данные:
# утренний такт сам, внутри прогона, повторяет сбор, если отказал невосполнимый
# источник (COLLECT_RETRY_*). Упавший шаг (код 1) — например, моргнувший push в
# репозиторий данных — systemd повторяет через 3 минуты, не больше трёх стартов
# за окно StartLimit (ops/budgets.json → restart).
#
# Запускается из systemd под пользователем dash (ops/systemd/sber850-*.service);
# env-файл читает сам (ENV_FILE), юниты его не читают. Откат — руками
# (ops/README.md §6):
#     sudo -u dash env ENV_FILE=/usr/local/etc/sber-850/env bash ops/run.sh rollback <sha>
set -Eeuo pipefail

PANEL="Сбер 850"

# Абсолютный путь к САМОМУ СЕБЕ — до любого `cd`: после обновления кода такт
# перезапускается этим файлом (шаг «обновление кода»), а относительный `$0`
# после `cd "$REPO_DIR"` указывал бы не туда.
SELF="$(cd -- "$(dirname -- "$0")" && pwd -P)/$(basename -- "$0")"

# Метка перезапуска (её ставит шаг «обновление кода» перед `exec`) нужна
# только САМОМУ скрипту и снимается из окружения сразу: иначе её унаследовали
# бы питон и тесты такта.
REEXEC_HEAD=${SBER_REEXEC:-}
unset SBER_REEXEC

MODE=${1:-daily}
case "$MODE" in
  collect|release-watch|daily|rebuild) ;;
  rollback)
    ROLLBACK_SHA=${2:-}
    ROLLBACK_NOTE=${3:-}
    [[ $ROLLBACK_SHA =~ ^[0-9a-f]{12,64}$ ]] || {
      echo "откат: run.sh rollback <хэш выпуска, от 12 шестнадцатеричных знаков> [\"причина\"]" >&2; exit 64; }
    ;;
  *) echo "режим: collect|release-watch|daily|rebuild|rollback <sha>" >&2; exit 64;;
esac

ENV_FILE=${ENV_FILE:-/usr/local/etc/sber-850/env}
[[ -r $ENV_FILE ]] || { echo "нет доступа к $ENV_FILE" >&2; exit 78; }
set -a; . "$ENV_FILE"; set +a

# ТОКЕН T-Invest — ТОЛЬКО СБОРЩИКУ T-Invest (docs/INTERFACES.md §8). Сразу после
# чтения env-файла токен уходит из окружения такта в неэкспортируемую переменную
# шелла и передаётся одной команде — `indicators.collect <режим> --only tinvest`
# (collect_once). Остальные сборщики, разбор новостей и PDF, нау-каст, pip,
# тесты, сборка и публикация идут без токена; юниты env-файл не читают вовсе
# (строки EnvironmentFile в них нет). Это гигиена окружения, а не граница
# доверия: env-файл читаем пользователем такта.
T_TOKEN=${TINVEST_TOKEN:-}
unset TINVEST_TOKEN

# Оба каталога обязательны. Запасной /tmp для состояния под PrivateTmp=yes дал
# бы КАЖДОМУ запуску свой приватный каталог, и замок перестал бы защищать что-
# либо; каталог кода «по месту скрипта» в песочнице тестов сбросил бы
# `git reset --hard` рабочее дерево разработчика.
[[ -n ${SBER_REPO_DIR:-} ]] || { echo "в $ENV_FILE не задан SBER_REPO_DIR" >&2; exit 78; }
[[ -n ${BANK_STATE_DIR:-} ]] || { echo "в $ENV_FILE не задан BANK_STATE_DIR" >&2; exit 78; }
REPO_DIR=$SBER_REPO_DIR
STATE_DIR=$BANK_STATE_DIR
VENV=${SBER_VENV:-$REPO_DIR/.venv}
PY=${SBER_PYTHON:-$VENV/bin/python}
# Отметка установленных зависимостей живёт В САМОМ venv: пересозданное
# окружение теряет её вместе с пакетами, и такт поставит их заново.
REQ_MARK="$VENV/.requirements.sha256"
cd "$REPO_DIR"
# Каталог кода — САМ клон git, а не каталог внутри чужого репозитория. Без своего
# `.git` git поднялся бы к ближайшему репозиторию выше, и `git fetch` с `git reset
# --hard origin/main` такта достались бы ему (каталог песочницы тестов лежит внутри
# рабочей копии разработчика; на сервере — опечатка в SBER_REPO_DIR). Отказ — до
# замка, журнала и любой команды git; потолок — на случай негодного `.git`.
[[ -e .git ]] || { echo "SBER_REPO_DIR ($REPO_DIR) — не клон git: в каталоге нет .git" >&2; exit 78; }
GIT_CEILING_DIRECTORIES=$(dirname -- "$(pwd -P)")
export GIT_CEILING_DIRECTORIES
mkdir -p "$STATE_DIR/logs"

# Русские строки под systemd уезжают в journald как есть; тот же скрипт руками
# из окружения с однобайтовой локалью ронял бы питон на UnicodeEncodeError.
export PYTHONIOENCODING=utf-8
# Переменные ядра и индикаторов — без префикса банка (BANK_*, docs/INTERFACES.md
# §8): копия ядра под другой банк их не меняет. Префикс банка (SBER_*) — только у
# переменных эксплуатации: слой ops у банка свой (docs/PORTING.md).
export BANK_STATE_DIR="$STATE_DIR"

# Сколько плановый такт (collect, daily) ждёт замок, занятый другим тактом:
# столько, сколько его может держать пересборка или дозор со сборкой — их
# потолок RuntimeMaxSec (расчёт — ops/budgets.json; равенство сверяет
# tests/test_ops_units.py). Дозор и пересборка на занятом замке не ждут — тихо
# выходят: следующая проверка через 10–15 минут.
LOCK_WAIT_SECONDS=4080

# Повтор сбора внутри утреннего такта — только когда отказал невосполнимый
# источник (отчёт сборщиков: retry; спрашивает `ops/tact.py retry`): всего не
# больше COLLECT_RETRY_ATTEMPTS попыток с паузой COLLECT_RETRY_PAUSE секунд.
# Числа — из ops/budgets.json (collect_retry), равенство сверяет
# tests/test_ops_units.py; время повторов входит в потолок юнита.
COLLECT_RETRY_ATTEMPTS=3
COLLECT_RETRY_PAUSE=180
# Режимы сборщиков, где есть сборщик T-Invest (indicators.sources.MODES; равенство
# сверяет tests/test_ops_tact.py): в них сбор идёт двумя командами.
TOKEN_MODES="collect daily-indicators"

# Каталоги кода и данных, которые считают число: их правка с опубликованного
# выпуска будит пересборку. Файлы `*.md` внутри (ops/README.md, записки книги) —
# документы и пересборку не будят. requirements.txt — тоже код: новая версия
# зависимости может сдвинуть число. Витрина (web/, functions/) выпуск не меняет.
CODE_DIRS=(model indicators ops data/assumptions data/facts data/indicators data/checks requirements.txt)
# Отметки в $BANK_STATE_DIR (ops/README.md, «Что где»):
#   release.commit — код выпуска, ПОДТВЕРЖДЁННОГО сверкой через боевую дверь
#                    (пишет ops/publish.py --verify);
#   release.pushed — выпуск в ветке, сверка ещё не прошла (её дожимает пересборка);
#   rebuild.tried  — коммит, на котором пересборка уже запускалась (пишет run.sh):
#                    упавшая пересборка не повторяется каждые 15 минут;
#   future.checked — «день код» прогона «в будущем» (пишет run.sh).
BUILT_MARK="$STATE_DIR/release.commit"
PUSHED_MARK="$STATE_DIR/release.pushed"
TRIED_MARK="$STATE_DIR/rebuild.tried"
# Тесты такта — БЕЛЫЙ СПИСОК: только тесты с меткой `tact` (pytest.ini). Новый
# тест без метки в такт не попадает, и такт не распухает сам собой (у 850oa он
# вырос с 7 до 22 минут). `not ci_only` — страховка и сигнал сторожу
# tests/conftest.py: полный выпуск в такте не считается. Быстрые тесты есть у
# каждого потока (ядро, книга, факты, индикаторы, витрина, контрольная модель,
# перезаякоривание, эксплуатация) — это сверяет tests/test_ops_tact_suite.py;
# весь набор — не дольше 3 минут на сервере (ops/budgets.json →
# tact_tests_target; замер — время шага «тесты такта» в журнале такта; шаг CI с
# тем же набором краснеет после 300 с — tact_tests_ci_ceiling).
# `not deadline` — тесты сроков данных в набор сервера не входят
# (docs/INTERFACES.md §9): истёкшее объяснение сработавшего гейта останавливает
# сама сборка (код 1), об истекающем сообщает плашка выпуска. Набор обязан быть
# зелёным на любой будущей дате.
TACT_TESTS="tact and not network and not archive and not docs and not ci_only and not deadline"
# Прогон «в будущем» в утреннем такте: день недели (1 — понедельник, `date +%u`)
# и сдвиг даты. Дублирует ежемесячный прогон CI (`schedule` в
# .github/workflows/ci.yml: 1-го числа весь набор с «сегодня» + 180 дней): GitHub
# выключает расписание публичного репозитория после 60 дней без активности, а
# тревога сервера доходит кодом 8. Набор — тот же TACT_TESTS, без тестов сроков:
# красным он бывает только из-за теста, привязанного к дате, — это дефект
# теста, а не будильник данных (docs/INTERFACES.md §6, §9).
FUTURE_WEEKDAY=${SBER_FUTURE_WEEKDAY:-1}
FUTURE_DAYS=${SBER_FUTURE_DAYS:-60}
FUTURE_MARK="$STATE_DIR/future.checked"

# Тихий замок проверок раз в 10–15 минут: занят — делать нечего, выход 0.
LOCKED=""
lock_quietly() {
  if command -v flock >/dev/null 2>&1; then
    exec 9>"$STATE_DIR/run.lock"
    flock -n 9 || exit 0
    LOCKED=1
  fi
}

if [[ $MODE == rebuild && -z $REEXEC_HEAD ]]; then
  # ── Тихая проверка пересборки ─────────────────────────────────────────────
  # Почти всегда делать нечего, и проверка обязана быть тихой: без шапки, без
  # строк в журнале файла и без обращения к источникам.
  lock_quietly
  pending_code=""
  if [[ -s $PUSHED_MARK ]]; then
    # Прошлый такт отправил выпуск, но сверка его не дождалась (сборка GitHub
    # Pages встала в очередь). Одна попытка — один GET: прошла — publish.py сам
    # пишет release.commit; нет — код выпуска запоминается, чтобы не
    # пересобирать и не пушить тот же код каждые 15 минут.
    if ! "$PY" ops/publish.py --verify --once; then
      pending_code=$(sed -n 's/^ *"code_commit": *"\([0-9a-f]*\)".*/\1/p' "$PUSHED_MARK" 2>/dev/null || true)
    fi
  fi
  if ! git fetch --quiet origin main 2>/dev/null; then
    # Моргнувший GitHub — не повод для тревоги: через 15 минут спросим снова.
    echo "пересборка: main на GitHub сейчас не читается — проверю через 15 минут" >&2
    exit 0
  fi
  target=$(git rev-parse origin/main)
  built=$(cat "$BUILT_MARK" 2>/dev/null || true)
  if [[ -n $built ]] && git diff --quiet "$built" "$target" -- "${CODE_DIRS[@]}" ':(exclude)*.md' 2>/dev/null; then
    exit 0
  fi
  if [[ -n $pending_code && $pending_code == "$target" ]]; then
    echo "пересборка: выпуск на коммите ${target:0:8} уже в репозитории данных и ждёт сверки — не пересобираю" >&2
    exit 0
  fi
  if [[ $(cat "$TRIED_MARK" 2>/dev/null || true) == "$target" ]]; then
    # Код 1 без работы: мост шлёт смену состояния, поэтому «упало» уже пришло
    # один раз и не повторяется, а «снова проходит» придёт, когда выпуск на этом
    # коде соберёт суточный такт или пересборку пройдёт новый коммит.
    echo "ПРОВАЛ (код 1): пересборка на коммите ${target:0:8} уже запускалась и не довела выпуск до витрины (журнал: journalctl -u sber850-rebuild) — повтор будет с новым коммитом в main, на этом коде выпуск соберёт суточный такт" >&2
    exit 1
  fi
  echo "$target" > "$TRIED_MARK"
fi

if [[ $MODE == release-watch && -z $REEXEC_HEAD ]]; then
  # ── Тихая проверка дозора ─────────────────────────────────────────────────
  # Таймер будит дозор каждые 10 минут в окне релизов по будням, а релизы
  # выходят несколько дней в месяц: вне окна релиза по календарю индикаторов и
  # без отложенного (принято, но не опубликовано) — выход без единой строки.
  lock_quietly
  "$PY" ops/tact.py window || exit 0
fi

# Лог в файл плюс journald. Нужны оба: journald ротируется по общему объёму
# машины, а разбирать инцидент недельной давности приходится по файлу.
# Перезапущенный после обновления кода такт уже пишет в тот же `tee`: второй
# `tee` поверх первого удвоил бы каждую строку файла.
LOG_FILE="$STATE_DIR/logs/$(date -u +%F).log"
if [[ -z $REEXEC_HEAD ]]; then
  exec > >(tee -a "$LOG_FILE") 2>&1
fi
find "$STATE_DIR/logs" -name '*.log' -mtime +45 -delete 2>/dev/null || true

STEP="старт"
step() { STEP="$*"; echo; echo "── $* ── $(date -u +%T)Z"; }
# Упавший шаг — всегда код 1, каким бы ни был код самой команды (он есть в
# строке журнала): иначе, например, 8 от случайной команды мост принял бы за
# тревогу при опубликованном выпуске.
fail() { echo "ПРОВАЛ на шаге «$STEP» (код $1). На витрине остаётся прежний выпуск." >&2; exit 1; }
trap 'fail $?' ERR

# Накопитель причин тревоги. Пустая строка означает «код 0»: тревога без
# названной причины бесполезна, поэтому текст и код всегда идут вместе.
ALARM=""
alarm_add() { ALARM="${ALARM:+$ALARM; }$1"; }

finish() {
  echo
  echo "готово: $(date -u +%FT%TZ)"
  if [[ -n $ALARM ]]; then
    echo "ТРЕВОГА (код 8): $ALARM" >&2
    exit 8
  fi
  exit 0
}

# Проба доставки тревоги: такт идёт как обычно, а в конце названный
# невосполнимый источник объявляется отказавшим — код 8. Переменная задаётся
# временной вставкой юнита (ops/README.md §4): мост dash-alert зовётся только
# из ExecStopPost, и запуск run.sh руками проверил бы код, но не доставку.
# Имя не из такта — код 64 (ops/tact.py simulate).
SIMULATE=${SBER_SIMULATE_FAILURE:-}
if [[ -n $SIMULATE ]]; then
  echo "ПРОБА ТРЕВОГИ: источник $SIMULATE будет объявлен отказавшим" >&2
fi

# Один проход сборщиков режима $1. В режимах со сборщиком T-Invest — двумя
# командами: первая (`--only tinvest`) одна на весь такт получает токен, вторая
# (`--skip tinvest`) — остальные сборщики и шаги такта (дозор, реестр
# дивидендов, ротация архива) уже на свежих данных T-Invest. Обе пишут один
# collector_report.json. Код — худший из двух: прочее (провал) > 3 > 0.
collect_once() {
  local mode=$1 rc_t=0 rc=0
  case " $TOKEN_MODES " in
    *" $mode "*)
      TINVEST_TOKEN="$T_TOKEN" "$PY" -m indicators.collect "$mode" --only tinvest || rc_t=$?
      "$PY" -m indicators.collect "$mode" --skip tinvest || rc=$?
      ;;
    *)
      "$PY" -m indicators.collect "$mode" || rc=$?
      ;;
  esac
  if [[ $rc_t != 0 && $rc_t != 3 ]]; then return "$rc_t"; fi
  if [[ $rc != 0 && $rc != 3 ]]; then return "$rc"; fi
  if [[ $rc_t == 3 || $rc == 3 ]]; then return 3; fi
  return 0
}

# Один вход к сборщикам для тактов сбора. Код 3 сборщиков — «работа закончена,
# но требует внимания»: такт обязан идти дальше и довести выпуск до витрины, а
# тревога уйдёт кодом 8 в самом конце. Прочее — падение шага (1 — отказ
# критического источника: при неполных входах на витрину не уходит ничего).
#
# ПОВТОР — только у утреннего такта и только когда отказал НЕВОСПОЛНИМЫЙ
# источник (его день потом не добрать; отчёт сборщиков ставит retry). Источник
# без токена, деградация восполнимого источника третий такт подряд и тревога
# реестра дивидендов — тревога без повтора: повтор их не снимет.
run_collect() {
  local mode=$1 rc=0 attempt=1
  if [[ -n $SIMULATE ]]; then
    "$PY" ops/tact.py simulate "$SIMULATE" "$mode" || { rc=$?; [[ $rc == 64 ]] && exit 64; fail "$rc"; }
  fi
  collect_once "$mode" || rc=$?
  while [[ $rc == 3 && $MODE == collect && $attempt -lt $COLLECT_RETRY_ATTEMPTS ]] && "$PY" ops/tact.py retry; do
    attempt=$((attempt + 1))
    echo "  невосполнимый источник не собран — повтор сбора через $COLLECT_RETRY_PAUSE с (попытка $attempt из $COLLECT_RETRY_ATTEMPTS)"
    sleep "$COLLECT_RETRY_PAUSE"
    rc=0
    collect_once "$mode" || rc=$?
  done
  case $rc in
    0) ;;
    3)
      if "$PY" ops/tact.py retry; then
        alarm_add "невосполнимый источник не собран (попыток: $attempt; строки выше) — пропущенный день не добирается никогда"
      else
        alarm_add "сбор требует внимания (строки выше): источник без токена, деградация источника третий такт подряд или тревога реестра дивидендов"
      fi
      ;;
    *) fail "$rc" ;;
  esac
  if [[ -n $SIMULATE ]]; then
    alarm_add "ПРОБА ТРЕВОГИ: источник $SIMULATE объявлен отказавшим — невосполнимый источник не собран"
  fi
}

# Тесты такта. Ноль выбранных тестов (pytest: код 5) — провал, а не успех:
# белый список, который никого не пускает, выключил бы проверку перед выпуском.
# Без второго -q (первый — в pytest.ini): итоговая строка «N passed in T s» в
# журнале такта — замер времени набора против цели tact_tests_target.
run_tact_tests() {
  local rc=0
  "$PY" -m pytest -m "$TACT_TESTS" || rc=$?
  case $rc in
    0) ;;
    5) echo "ни одного теста с меткой tact: проверять нечего, выпуск без проверок не выходит" >&2; fail 5 ;;
    *) fail "$rc" ;;
  esac
}

# Нау-каст: прогноз фиксируется в журнале ДО выхода факта — иначе сравнивать
# будет не с чем. Код 3 — «записано не всё» (нет ожидания модели, дисциплина
# журнала): выпуск от нау-каста не зависит (к цене он не подключён), тревога —
# в конце такта.
run_nowcast() {
  step "нау-каст ближайшего отчёта"
  local rc=0
  "$PY" -m indicators.collect nowcast || rc=$?
  case $rc in
    0) ;;
    3) alarm_add "нау-каст записан не целиком (строки «ВНИМАНИЕ:» выше) — журнал прогнозов неполон" ;;
    *) fail "$rc" ;;
  esac
}

# Выпуск: клон данных, сборка, публикация, сверка. Общий хвост дозора, суточного
# такта и пересборки — у выпуска один путь на витрину.
build_and_publish() {
  step "клон репозитория данных"
  # Сборка берёт прошлый выпуск и историю оценки из клона ветки release: он
  # обязан совпадать с веткой (откат с ноутбука, чужой push). Отказ — не
  # провал: публикация обновит клон сама и назовёт свой отказ.
  "$PY" ops/publish.py --sync || echo "  ВНИМАНИЕ: клон ветки release не обновлён (строки выше) — прошлый выпуск для сборки берётся из прежнего клона" >&2

  step "сборка выпуска"
  # Три исхода (docs/INTERFACES.md §6). ОТКАЗ, код 1 — нарушенный инвариант,
  # сломанный контракт, сработавший гейт без действующего объяснения (нет записи,
  # срок истёк или масса вне коридора ожидания), защита заголовка, нет цены
  # главного тикера: такт останавливается, на витрине остаётся прежний выпуск.
  # ТРЕВОГА, код 3 — выпуск собран и записан, но требует человека: деградировал
  # живой вход оценки (цена, запись реестра, кривая, ключевая) или источник,
  # уже получивший код 3 у сборщиков; нет записи реестра дивидендов за год к
  # концу квартала ГОСА; выпуск от 400 000 байт — публиковать можно, тревога
  # уйдёт в конце такта. ПЛАШКА, код 0 — объяснение сработавшего гейта истекает
  # в ближайшие 30 дней или истёк срок документа эмитента: флаги выпуска
  # `explanation_expiring`, `policy_expired`; такт о них не тревожит.
  local rc=0
  "$PY" -m model.build_release || rc=$?
  case $rc in
    0) ;;
    3) alarm_add "сборка подняла тревогу (строки «тревога:» выше): живые входы оценки деградировали, нет записи реестра дивидендов к концу квартала ГОСА или выпуск тяжёлый — выпуск опубликован" ;;
    *) fail "$rc" ;;
  esac

  step "публикация в репозиторий данных"
  # Сначала неизменяемый releases/<sha256>.json, потом указатель, история и
  # журнал — одним коммитом; push с повтором. Отказ — код 1: systemd повторит
  # такт через 3 минуты. Код 3 — выпуск в ветке, но журнал прогнозов не выгружен
  # или дерево ветки данных доросло до порога сторожа объёма.
  rc=0
  "$PY" ops/publish.py || rc=$?
  case $rc in
    0) ;;
    3) alarm_add "выпуск опубликован, но публикация требует внимания (строки «ПУБЛИКАЦИЯ:» выше)" ;;
    *) fail "$rc" ;;
  esac
  "$PY" ops/tact.py done || echo "  ВНИМАНИЕ: отложенное дозора не снято — следующий дозор соберёт выпуск ещё раз (публикация повтор не продублирует)" >&2

  step "сверка через боевую дверь"
  # Читаем ЧЕРЕЗ ТУ ЖЕ дверь, что и браузер, до совпадения хэша и published_at.
  # Код 3 — выпуск в ветке, но GitHub Pages его не отдал за отведённое время
  # (или витрина живёт на запасном источнике): тревога, а не провал — выпуск
  # уже ушёл, сверку дожмёт пересборка, release.commit появится только после неё.
  rc=0
  "$PY" ops/publish.py --verify || rc=$?
  case $rc in
    0) ;;
    3) alarm_add "выпуск отправлен в репозиторий данных, но боевая дверь не подтвердила его (строки «СВЕРКА:» выше) — сверку дожмёт пересборка" ;;
    *) fail "$rc" ;;
  esac
}

echo "=============================================================="
echo "$PANEL · такт $MODE · $(date -u +%FT%TZ) · $REPO_DIR"
if [[ -n $REEXEC_HEAD ]]; then
  echo "(перезапуск тем же тактом: код обновлён до ${REEXEC_HEAD:0:8}, исполняется новый ops/run.sh)"
fi
echo "=============================================================="

# Замок один на все такты и на откат: сбор и суточный прогон пишут в одно
# состояние, публикация и откат — в один клон ветки release. Перезапущенный
# такт наследует дескриптор 9 от самого себя до `exec` — вместе с уже взятым
# замком; пересборка и дозор взяли его ещё на тихой проверке. Открыть файл
# заново значило бы отпустить замок и взять его снова: между этими двумя
# мгновениями его мог бы перехватить другой такт.
if [[ -n $REEXEC_HEAD || -n $LOCKED ]] && { : >&9; } 2>/dev/null; then
  :
else
  exec 9>"$STATE_DIR/run.lock"
fi
if command -v flock >/dev/null 2>&1; then
  if ! flock -n 9; then
    echo "  замок у другого такта (например, у пересборки) — жду до ${LOCK_WAIT_SECONDS} с"
    # Код 75 (EX_TEMPFAIL), а не 0: при нулевом мост отрапортовал бы
    # «снова проходит», хотя не выполнилось ничего. Юнит перезапустится сам.
    flock -w "$LOCK_WAIT_SECONDS" 9 || { echo "прогон уже идёт, выхожу" >&2; exit 75; }
  fi
else
  echo "  ВНИМАНИЕ: flock не найден — прогон БЕЗ защиты от параллельного запуска"
fi

if [[ $MODE == rollback ]]; then
  # Откат — пауза на один такт, а не состояние: ближайший выпуск (суточный такт,
  # дозор или пересборка на новом коммите) перепишет указатель. Если причина
  # не устранена — остановить таймеры (ops/README.md, «Откат»). Кода откат не
  # обновляет: он должен быть быстрым и делать ровно одно.
  step "откат указателя latest.json на ${ROLLBACK_SHA:0:12}"
  # Причина — строкой в history.json репозитория данных (видна рядом с выпуском).
  "$PY" ops/publish.py --rollback "$ROLLBACK_SHA" ${ROLLBACK_NOTE:+--note "$ROLLBACK_NOTE"}
  step "сверка через боевую дверь"
  rc=0
  "$PY" ops/publish.py --verify || rc=$?
  case $rc in
    0) ;;
    3) alarm_add "откат отправлен в репозиторий данных, но боевая дверь его не подтвердила (строки «СВЕРКА:» выше)" ;;
    *) fail "$rc" ;;
  esac
  finish
fi

step "обновление кода"
if ! git fetch --quiet origin main; then
  # Моргнувший GitHub не должен стоить невосполнимого дня сбора: такт идёт на
  # текущем коде, новый подхватит следующий. Публикация (тот же GitHub)
  # откажет сама и назовёт себя.
  echo "  ВНИМАНИЕ: main на GitHub не читается — такт идёт на текущем коде $(git rev-parse --short HEAD)" >&2
else
  local_head=$(git rev-parse HEAD)
  remote_head=$(git rev-parse origin/main)
  if [[ $local_head == "$remote_head" ]]; then
    echo "  HEAD не менялся: ${local_head:0:8}"
  else
    echo "  код обновился ${local_head:0:8} -> ${remote_head:0:8}; сбрасываю дерево"
    # Безопасно: данные сбора и выпуски в git не коммитятся (var/ в .gitignore,
    # состояние — в $BANK_STATE_DIR), сбрасывается только код и входы книги.
    git reset --hard --quiet origin/main
    # ПЕРЕЗАПУСК НОВЫМ run.sh. bash читает скрипт по ходу исполнения из уже
    # открытого файла, а `git reset --hard` кладёт на диск НОВЫЙ файл: такт до
    # конца исполнял бы ПРЕЖНИЙ run.sh (у 850oa подтверждено журналом такта).
    # `exec` заменяет процесс тем же PID — systemd видит тот же юнит, замок и
    # журнал наследуются, — и новый файл проходит такт с начала. Перезапуск
    # один на такт (метка SBER_REEXEC): второе обновление за такт вступит в
    # силу со следующего.
    if [[ -z $REEXEC_HEAD ]]; then
      echo "  перезапускаю такт новым ops/run.sh"
      export SBER_REEXEC="$remote_head"
      exec "$BASH" "$SELF" "$@"
    fi
    echo "  ВНИМАНИЕ: код обновился повторно за один такт (${REEXEC_HEAD:0:8} -> ${remote_head:0:8}); перезапуск уже был — новый ops/run.sh вступит в силу со следующего такта"
  fi
fi
echo "  HEAD: $(git rev-parse --short HEAD)"

step "зависимости"
# По отметке sha256(requirements.txt) — КАЖДЫЙ такт, а не только при смене
# HEAD: упавший pip (PyPI недоступен) иначе не повторился бы, и новый код
# работал бы на старых пакетах. Отметка пишется только после удачной
# установки, неудача — провал такта (код 1).
req_sha=$(sha256sum requirements.txt | cut -d' ' -f1)
req_had=$(cat "$REQ_MARK" 2>/dev/null || true)
if [[ $req_had == "$req_sha" ]]; then
  echo "  на месте: requirements.txt ${req_sha:0:12}"
else
  echo "  requirements.txt ${req_had:0:12}${req_had:+ -> }${req_sha:0:12}: ставлю"
  "$PY" -m pip install --quiet --disable-pip-version-check -r requirements.txt
  echo "$req_sha" > "$REQ_MARK"
fi

if [[ $MODE == rebuild ]]; then
  # Входы — те, что собрал последний такт: цены, кривая, ряды, журнал
  # прогнозов. Меняется только код. Тесты — те же, что у суточного такта, и до
  # сборки: пересборка появилась ради правок кода, а не в обход проверок.
  step "тесты такта"
  run_tact_tests
  build_and_publish
  finish
fi

if [[ $MODE == release-watch ]]; then
  step "дозор релизов"
  # Новость и статический PDF дня релиза; месяц РСБУ принимается при
  # совпадении двух источников (indicators/release_watch.py). Вне окна релиза
  # сборщик сам ответит «пропуск».
  run_collect release-watch
  step "что принято"
  # 0 — принят месяц РСБУ или новый кандидат МСФО (или отложен с прошлого
  # такта): выпуск; 1 — нового нет; прочее — провал шага.
  rc=0
  "$PY" ops/tact.py news || rc=$?
  case $rc in
    0)
      run_nowcast
      step "тесты такта"
      run_tact_tests
      build_and_publish
      ;;
    1) ;;
    *) fail "$rc" ;;
  esac
  finish
fi

step "сбор источников"
if [[ $MODE == daily ]]; then
  run_collect daily-indicators
else
  run_collect collect
fi

if [[ $MODE == collect ]]; then
  if [[ $(date -u +%u) == "$FUTURE_WEEKDAY" ]]; then
    step "тесты такта «в будущем» (+$FUTURE_DAYS дней)"
    # Тест, привязанный к дате, остановит суточный такт в тот день, когда она
    # наступит. Здесь это видно за FUTURE_DAYS дней — тревогой, а не
    # блокировкой: сегодня выпускать ничто не мешает. Сроки данных (объяснения
    # гейтов, документы эмитента) набор не проверяет: о них сообщают плашки
    # выпуска. Итог дня помнится в future.checked: повтор юнита после провала
    # шага (код 1) не гоняет тесты заново, а повторяет итог.
    today=$(date -u +%F)
    future=$(date -u -d "+$FUTURE_DAYS days" +%F)
    read -r checked_day checked_rc < "$FUTURE_MARK" 2>/dev/null || true
    if [[ ${checked_day:-} == "$today" && ${checked_rc:-} =~ ^[0-9]+$ ]]; then
      rc=$checked_rc
      echo "  уже проверено сегодня (код $rc) — повтор юнита тесты заново не гоняет"
    else
      rc=0
      FAKE_TODAY=$future "$PY" -m pytest -m "$TACT_TESTS" || rc=$?
      echo "$today $rc" > "$FUTURE_MARK"
    fi
    [[ $rc == 0 ]] || alarm_add "тесты такта с FAKE_TODAY=$future падают (код $rc, строки выше): через $FUTURE_DAYS дней суточный такт остановится — тест привязан к дате, поправить тест"
  fi

  step "объём состояния"
  rc=0
  "$PY" -m indicators.collect status || rc=$?
  [[ $rc == 0 ]] || alarm_add "сводка объёма состояния не прошла (код $rc, строки выше)"

  step "здоровье состояния"
  # ТРЕВОГА, А НЕ БЛОКИРОВКА — и здесь, в отличие от суточного такта, она
  # обязана дойти кодом: утренний такт единственный, кто спрашивает о
  # здоровье состояния каждый день.
  if ! "$PY" -m indicators.collect health; then
    alarm_add "состояние не в порядке (строки «ТРЕВОГА:» выше)"
  fi

  finish
fi

run_nowcast

step "здоровье состояния"
# Напоминание, а не тревога: о нездоровом состоянии владелец уже узнал кодом
# утреннего такта, который спрашивает то же самое.
if ! "$PY" -m indicators.collect health; then
  echo "  ВНИМАНИЕ: состояние не в порядке (см. строки выше). Выпуск продолжается." >&2
fi

step "тесты такта"
# ДО сборки: выпуск с нарушенными инвариантами не должен уйти на витрину.
run_tact_tests

build_and_publish

step "объём состояния"
# После публикации и сверки: выпуск уже на витрине, сводка — только отчёт.
# Её отказ — тревога такта, а не «ПРОВАЛ … на витрине прежний выпуск».
"$PY" -m indicators.collect status || alarm_add "сводка объёма состояния упала (выпуск опубликован; строки выше)"

finish
